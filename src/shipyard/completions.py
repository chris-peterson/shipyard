"""zsh tab completion for the shipyard CLI, and its one-command install.

The script is generated from ``cli.build_parser()`` rather than written by hand,
so a new subcommand or flag is offered the moment it is declared: the command
list can't drift from the parser because it *is* the parser. ``tests/
test_completions.py`` still asserts the two agree, so a change to this generator
that drops a command fails there rather than going unnoticed at a prompt.

Dynamic values are read at ``<TAB>`` time, in shell only: plugin names come from
the ``plugins:`` list of the aggregator in ``--root`` (else the current
directory, else the one sibling of it carrying ``plugins.yml`` — the same
resolution ``onboarding`` uses).
"""
from __future__ import annotations

import argparse
import pathlib
import re

COMPLETIONS_DIR = pathlib.Path(".zsh") / "completions"
FPATH_LINE = "fpath=(~/.zsh/completions $fpath)"
COMPINIT_LINES = "autoload -Uz compinit && compinit"

# A positional whose values are plugin names on the aggregator's roster.
PLUGIN_POSITIONALS = {"names"}

HEADER = r"""#compdef shipyard
# Generated by `shipyard completions zsh` from shipyard's own parser — do not edit.

# Plugin names from the aggregator's plugins.yml: --root's, else the current
# directory's, else the one sibling's that has one.
_shipyard_plugins() {
  local root=. i manifest
  for (( i = 2; i < CURRENT; i++ )); do
    [[ ${words[i]} == --root ]] && root=${words[i+1]/#\~/$HOME}
  done
  if [[ -r $root/plugins.yml ]]; then
    manifest=$root/plugins.yml
  else
    local -a found
    found=( $root/../*/plugins.yml(N) )
    (( ${#found} == 1 )) && manifest=${found[1]}
  fi
  [[ -n $manifest ]] || return 1
  local -a names
  names=( ${(f)"$(awk '
    /^plugins:/ { on = 1; next }
    on && /^[^ #-]/ { on = 0 }
    on && /^[ ]*- / { sub(/^[ ]*- */, ""); sub(/[ ]*#.*/, ""); print }
  ' $manifest 2>/dev/null)"} )
  (( ${#names} )) && _describe -t plugins 'plugin' names
}
"""


def _subparsers(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def _helps(parser: argparse.ArgumentParser) -> dict[str, str]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return {a.dest: a.help or "" for a in action._choices_actions}
    return {}


def _q(text: str) -> str:
    """Single-quote for zsh."""
    return "'" + text.replace("'", "'\\''") + "'"


def _help(text: str | None) -> str:
    """Help text for a spec's [...] slot, which can't hold brackets."""
    text = " ".join((text or "").split())
    text = text.replace("[", "(").replace("]", ")")
    return text.replace("\\", "")


def _action_spec(action: argparse.Action) -> str:
    if action.choices:
        return f"({' '.join(map(str, action.choices))})"
    if action.dest == "root":
        return "_files -/"
    if action.dest.endswith("file"):
        return "_files"
    if action.dest in PLUGIN_POSITIONALS:
        return "_shipyard_plugins"
    return " "


def _arg_specs(parser: argparse.ArgumentParser) -> list[str]:
    specs = []
    for action in parser._actions:
        if isinstance(action, argparse._HelpAction):
            specs.append("'(- *)'{-h,--help}'[show help]'")
            continue
        message = (action.metavar or action.dest).replace(":", "")
        if not action.option_strings:
            prefix = "*" if action.nargs in ("*", "+") else ""
            specs.append(_q(f"{prefix}:{message}:{_action_spec(action)}"))
            continue
        value = f":{message}:{_action_spec(action)}" if action.nargs != 0 else ""
        for flag in action.option_strings:
            specs.append(_q(f"{flag}[{_help(action.help)}]{value}"))
    return specs


def commands(parser: argparse.ArgumentParser) -> list[str]:
    return list(_subparsers(parser))


def script(parser: argparse.ArgumentParser) -> str:
    subs = _subparsers(parser)
    helps = _helps(parser)
    describe = "\n".join(f"    {_q(name + ':' + _help(helps.get(name)))}" for name in subs)
    arms = []
    for name, sub in subs.items():
        specs = " \\\n            ".join(_arg_specs(sub))
        arms.append(f"        {name})\n          _arguments -s \\\n            {specs} ;;")
    return (
        HEADER
        + "\n_shipyard() {\n"
        + "  local curcontext=$curcontext state line\n"
        + "  typeset -A opt_args\n"
        + "  _arguments -C '(- *)'{-h,--help}'[show help]' '1: :->command' '*:: :->args'\n"
        + "  case $state in\n"
        + "    command)\n"
        + "      local -a commands\n"
        + f"      commands=(\n{describe}\n      )\n"
        + "      _describe -t commands 'shipyard command' commands ;;\n"
        + "    args)\n"
        + "      case $line[1] in\n"
        + "\n".join(arms) + "\n"
        + "      esac ;;\n"
        + "  esac\n"
        + "}\n\n"
        + '_shipyard "$@"\n'
    )


def _wire_zshrc(rc: pathlib.Path) -> str:
    """Put the completions dir on fpath *before* compinit runs — appended after
    it, the directory is searched too late and nothing loads."""
    text = rc.read_text() if rc.exists() else ""
    has_fpath = ".zsh/completions" in text
    lines = text.splitlines(keepends=True)
    compinit_at = next((i for i, l in enumerate(lines)
                        if re.search(r"\bcompinit\b", l) and not l.lstrip().startswith("#")), None)
    if has_fpath and compinit_at is not None:
        return "already wired"
    if compinit_at is not None:
        lines.insert(compinit_at, FPATH_LINE + "\n")
        rc.write_text("".join(lines))
        return f"added fpath before compinit in {rc}"
    tail = "" if not text or text.endswith("\n") else "\n"
    add = ("" if has_fpath else FPATH_LINE + "\n") + COMPINIT_LINES + "\n"
    rc.write_text(text + tail + add)
    return f"appended {'compinit' if has_fpath else 'fpath and compinit'} to {rc}"


def install(parser: argparse.ArgumentParser, home: pathlib.Path | None = None) -> list[str]:
    """Write ~/.zsh/completions/_shipyard and wire ~/.zshrc. Idempotent."""
    home = home or pathlib.Path.home()
    target = home / COMPLETIONS_DIR / "_shipyard"
    target.parent.mkdir(parents=True, exist_ok=True)
    body = script(parser)
    wrote = not target.exists() or target.read_text() != body
    if wrote:
        target.write_text(body)
    return [f"{'wrote' if wrote else 'unchanged'} {target}", _wire_zshrc(home / ".zshrc")]


def run(shell: str, *, print_only: bool) -> int:
    from .cli import build_parser
    parser = build_parser()
    if print_only:
        print(script(parser), end="")
        return 0
    for line in install(parser):
        print(line)
    print("restart your shell (exec zsh) to pick it up")
    return 0
